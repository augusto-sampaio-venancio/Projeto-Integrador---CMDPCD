  <script>
    document.addEventListener('DOMContentLoaded', () => {
      const modal = document.getElementById('presidente-modal');
      const modalFoto = document.getElementById('pres-modal-foto');
      const modalNome = document.getElementById('pres-modal-nome');
      const modalGestao = document.getElementById('pres-modal-gestao');
      const modalBiografia = document.getElementById('pres-modal-biografia');
      const modalClose = document.getElementById('pres-modal-close');

      function openModal(data) {
        modalFoto.src = data.foto;
        modalFoto.alt = `Foto de ${data.nome}`;
        modalNome.textContent = data.nome;
        modalGestao.textContent = data.gestao;
        modalBiografia.textContent = data.biografia;

        modal.classList.remove('hidden');
        setTimeout(() => {
          modal.classList.remove('opacity-0');
          modal.querySelector('.transform').classList.remove('scale-95');
        }, 10);
      }

      function closeModal() {
        modal.classList.add('opacity-0');
        modal.querySelector('.transform').classList.add('scale-95');
        setTimeout(() => {
          modal.classList.add('hidden');
        }, 300);
      }

      document.addEventListener('click', (e) => {
        const btn = e.target.closest('.btn-ler-presidente');
        if (!btn) return;

        e.preventDefault();
        const data = {
          nome: btn.getAttribute('data-nome'),
          gestao: btn.getAttribute('data-gestao'),
          biografia: btn.getAttribute('data-biografia'),
          foto: btn.getAttribute('data-foto')
        };
        openModal(data);
      });

      if (modalClose) modalClose.addEventListener('click', closeModal);
      if (modal) {
        modal.addEventListener('click', (e) => {
          if (e.target === modal) closeModal();
        });
        document.addEventListener('keydown', (e) => {
          if (e.key === 'Escape' && !modal.classList.contains('hidden')) {
            closeModal();
          }
        });
      }
    });
  </script>

