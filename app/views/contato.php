    <script>
      document.addEventListener('DOMContentLoaded', () => {
        const form = document.getElementById('form-contato');
        const alertBox = document.getElementById('form-alert');
        const btnEnviar = document.getElementById('btn-enviar');

        form.addEventListener('submit', (e) => {
          e.preventDefault();

          // Estado de carregamento
          btnEnviar.disabled = true;
          btnEnviar.innerHTML = `<i data-lucide="loader-2" class="w-4 h-4 animate-spin"></i> Enviando...`;
          if (typeof lucide !== 'undefined') {
            lucide.createIcons();
          }

          const formData = new FormData(form);

          fetch('<?= BASE_URL ?>/contato/enviar', {
            method: 'POST',
            body: formData
          })
          .then(res => res.json())
          .then(data => {
            alertBox.classList.remove('hidden', 'bg-destructive/10', 'text-destructive', 'border-destructive/20', 'bg-emerald-500/10', 'text-emerald-500', 'border-emerald-500/20');
            
            if (data.status === 'success') {
              alertBox.classList.add('bg-emerald-500/10', 'text-emerald-500', 'border-emerald-500/20');
              alertBox.innerHTML = `<div class="flex items-center gap-2"><i data-lucide="check-circle" class="w-4 h-4"></i> ${data.message}</div>`;
              form.reset();
            } else {
              alertBox.classList.add('bg-destructive/10', 'text-destructive', 'border-destructive/20');
              alertBox.innerHTML = `<div class="flex items-center gap-2"><i data-lucide="alert-circle" class="w-4 h-4"></i> ${data.message}</div>`;
            }
            alertBox.classList.remove('hidden');
            if (typeof lucide !== 'undefined') {
              lucide.createIcons();
            }
          })
          .catch(err => {
            alertBox.classList.remove('hidden', 'bg-emerald-500/10', 'text-emerald-500', 'border-emerald-500/20');
            alertBox.classList.add('bg-destructive/10', 'text-destructive', 'border-destructive/20');
            alertBox.innerHTML = `<div class="flex items-center gap-2"><i data-lucide="alert-circle" class="w-4 h-4"></i> Ocorreu um erro de rede. Tente novamente mais tarde.</div>`;
            alertBox.classList.remove('hidden');
            if (typeof lucide !== 'undefined') {
              lucide.createIcons();
            }
          })
          .finally(() => {
            btnEnviar.disabled = false;
            btnEnviar.innerHTML = `<i data-lucide="send" class="w-4 h-4"></i> Enviar Mensagem`;
            if (typeof lucide !== 'undefined') {
              lucide.createIcons();
            }
          });
        });
      });
    </script>
